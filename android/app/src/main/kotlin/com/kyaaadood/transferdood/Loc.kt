/** Idioma de la interfaz: automático (según el teléfono), español o inglés. */
object Loc {
    @Volatile var setting: String = "auto"

    val english: Boolean
        get() = when (setting) {
            "en" -> true
            "es" -> false
            else -> Locale.getDefault().language != "es"
        }

    /** Traduce un texto escrito en español (si el idioma es inglés). */
    fun t(es: String): String = if (english) en[es] ?: es else es

    /** Traduce una plantilla con {0}, {1}… y la rellena. */
    fun f(es: String, vararg args: Any?): String {
        var s = t(es)
        for (i in args.indices) s = s.replace("{" + i + "}", args[i].toString())
        return s
    }

